#!/usr/bin/env python3
"""Writes third_party/THIRD_PARTY_NOTICES.md: what the `tesserae-engine` wheel bundles, and under what licence.

TRE-REQ-025. Three parts:

* the Rust crates `engine-py` links (normal dependencies, every target, read from `cargo metadata`), each with
  its licence expression, authors and the licence files its package ships; files with identical text are
  printed once and the crates that carry them listed under it;
* the fonts embedded with `include_bytes!` (hand-written table below; texts in third_party/fonts/);
* the shared libraries `auditwheel` copies into the Linux wheels (table below; texts in third_party/system-libs/).

Run it after the dependency tree changes; `--check` exits 1 when the committed file is stale (CI's docs job).
Needs the crates in the local cargo registry (`cargo fetch`). Standard library only.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "third_party" / "THIRD_PARTY_NOTICES.md"
LICENCE_NAMES = ("licen", "copying", "copyright", "notice", "unlicense")

FONTS = [
    ("Roboto Regular, Roboto Medium", "Copyright 2011 Google Inc.", "Apache-2.0", "fonts/LICENSE-Roboto-Apache-2.0.txt"),
    ("Noto Sans Arabic Regular", "Copyright 2022 The Noto Project Authors", "OFL-1.1", "fonts/LICENSE-NotoSansArabic-OFL-1.1.txt"),
    (
        "Hack Nerd Font Mono Regular",
        "Copyright 2018 Source Foundry Authors; derived from DejaVu (public domain) and Bitstream Vera",
        "MIT (the file also records the DejaVu and Bitstream Vera terms)",
        "fonts/LICENSE-HackNerdFontMono.txt",
    ),
]
SYSTEM_LIBS = [
    ("bzip2-libs", "bzip2-1.0.6", "system-libs/LICENSE-bzip2.txt"),
    ("fontconfig", "HPND-style (fontconfig)", "system-libs/LICENSE-fontconfig.txt"),
    ("freetype", "FTL (FreeType Project License), or GPL-2.0-or-later", "system-libs/LICENSE-freetype-FTL.txt"),
    ("libpng", "libpng-2.0", "system-libs/LICENSE-libpng.txt"),
    ("libuuid (util-linux)", "BSD-3-Clause", "system-libs/LICENSE-libuuid-BSD-3-Clause.txt"),
]


def crates() -> list[dict]:
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=ROOT, check=True, capture_output=True, text=True,
        ).stdout
    )
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "engine-py")
    seen, stack = set(), [root]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):  # normal, not dev or build
                stack.append(dep["pkg"])
    # Our own workspace crates are covered by the project LICENSE.
    return sorted(
        (by_id[p] for p in seen if by_id[p]["source"] is not None),
        key=lambda p: (p["name"], p["version"]),
    )


def licence_files(pkg: dict) -> list[pathlib.Path]:
    folder = pathlib.Path(pkg["manifest_path"]).parent
    found = []
    for path in sorted(folder.iterdir()):
        if path.is_file() and any(w in path.name.lower() for w in LICENCE_NAMES) and path.suffix in ("", ".md", ".txt"):
            found.append(path)
    return found


def render() -> str:
    packages = crates()
    texts: dict[str, str] = {}
    carriers: dict[str, list[str]] = {}
    rows, missing = [], []
    for pkg in packages:
        label = f"{pkg['name']} {pkg['version']}"
        expr = pkg["license"] or (f"see {pkg['license_file']}" if pkg["license_file"] else "unspecified")
        authors = "; ".join(a.split("<")[0].strip() for a in pkg["authors"]) or "the crate's authors"
        files = licence_files(pkg)
        rows.append((label, expr, authors))
        if not files:
            missing.append(label)
        for f in files:
            body = f.read_text(encoding="utf-8", errors="replace").strip()
            key = hashlib.sha256(body.encode()).hexdigest()
            texts[key] = body
            carriers.setdefault(key, []).append(label)
    out = [
        "# Third-party notices",
        "",
        "The `tesserae-engine` wheel (import name `tess_re`) is MIT-licensed (`LICENSE`). It also contains the",
        "software below, each under its own licence. Generated by `tools/gen_third_party_notices.py`; do not edit.",
        "",
        "## Fonts",
        "",
        "Embedded in the engine binary. The full licence texts are in `fonts/`.",
        "",
        "| Font | Copyright | Licence | Text |",
        "|---|---|---|---|",
    ]
    out += [f"| {n} | {c} | {lic} | `{t}` |" for n, c, lic, t in FONTS]
    out += [
        "",
        "## Shared libraries added to the Linux wheels",
        "",
        "`auditwheel` copies these into the manylinux wheels (not the macOS or Windows wheels). The texts are in `system-libs/`.",
        "",
        "| Library | Licence | Text |",
        "|---|---|---|",
    ]
    out += [f"| {n} | {lic} | `{t}` |" for n, lic, t in SYSTEM_LIBS]
    out += [
        "",
        f"## Rust crates ({len(rows)})",
        "",
        "Statically linked. Where a crate offers a choice of licences (`OR`), the engine may be used under any one of them.",
        "",
        "| Crate | Licence | Authors |",
        "|---|---|---|",
    ]
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    if missing:
        out += [
            "",
            f"{len(missing)} crates ship no licence file in their package; they are licensed as the table says,",
            "by the authors it names: " + ", ".join(missing) + ".",
        ]
    out += ["", "## Licence texts of the crates", ""]
    for key in sorted(texts, key=lambda k: (-len(carriers[k]), carriers[k][0])):
        who = carriers[key]
        shown = ", ".join(who[:40]) + (f", and {len(who) - 40} more" if len(who) > 40 else "")
        out += [f"### Used by: {shown}", "", "```text", texts[key], "```", ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 tools/gen_third_party_notices.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
